  windowStartHour: 10,
  windowEndHour: 19,
  /** Предохранители одного прогона: не засыпать Gemini и не слать пачку сообщений разом (риск блокировки номера). */
  maxSummariesPerPass: 10,
  maxSendsPerPass: 5,
  /** После стольких неудачных отправок касание отменяется и лид закрывается. */
  maxSendAttempts: 3,
